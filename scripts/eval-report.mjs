#!/usr/bin/env node
// Assembles docs/memory-agent/evaluation-results.md from the measured metrics
// the evaluation suites wrote to .eval-out/. Never run with fabricated data:
// the JSON inputs come straight from `vitest run -c vitest.eval.config.ts`.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const read = (name) => JSON.parse(readFileSync(join('.eval-out', `${name}.json`), 'utf8'))
const improvement = read('improvement')
const staleness = read('staleness')
const safety = read('safety')

const row = (label, s) =>
  `| ${label} | ${s.actions} | ${s.failures} | ${s.recoveries} | ${s.modelCalls} | ${s.contextChars ?? '—'} |`

const configTable = (config, sessions) =>
  [
    `### ${config}`,
    '',
    '| Session | Actions | Failed actions | Recoveries | Planning calls | Memory context (chars) |',
    '| --- | --- | --- | --- | --- | --- |',
    ...sessions.map((s, i) => row(`${i + 1}`, s)),
    '',
  ].join('\n')

const stalenessTable = [
  '| Session | Portal | Actions | Failed actions | Recoveries | Planning calls |',
  '| --- | --- | --- | --- | --- | --- |',
  ...Object.entries(staleness.sessions).map(
    ([k, s]) =>
      `| ${k} | ${k.startsWith('v1') ? 'v1' : 'v2'} | ${s.actions} | ${s.failures} | ${s.recoveries} | ${s.modelCalls} |`,
  ),
].join('\n')

const md = `# Evaluation Results

Generated by \`pnpm evaluate:memory\` on ${new Date().toISOString().slice(0, 10)}. All numbers
are **measured** by the harness in \`tests/evaluation/\` — nothing here is hand-written.

## Harness design (read before comparing numbers)

The harness runs the **real memory subsystem** (event ledger, write pipeline, episode/
reflection learning, hybrid retrieval, skill lifecycle: shadow → trust → degrade → repair)
against a deterministic simulator of the demo invoice portal (\`demo/portals\`), driven by a
**scripted planner of constant competence**. The planner follows a fixed policy (use an
offered workflow → else a remembered site fact → else explore in fixed order), so differences
between configurations measure what the memory system delivers to the planner — not model
skill. It does not measure LLM behaviour, tokens, or wall-clock latency; those require the
end-to-end browser demo (docs/demo-script.md). "Planning calls" counts the scripted planner's
plan/observe/replan rounds — the quantity a real deployment pays model calls for.

## Repeated-task improvement (task: "${improvement.goal}")

${Object.entries(improvement.configs)
  .map(([config, sessions]) => configTable(config, sessions))
  .join('\n')}

## Site change: stale memory → recovery → supersession → degradation → repair

Story: ${staleness.story}

${stalenessTable}

Verified by the suite: the outdated "Billing is under Settings" fact is **superseded** (kept
for provenance with \`validUntil\` + contradiction link, excluded from retrieval); the trusted
workflow **degrades** after repeated verified failures instead of retrying forever; repair
mints **version 2 in shadow** chained to the original; the repaired workflow restores
low-cost runs on the changed site.

## Safety

| Metric | Result |
| --- | --- |
| Prompt-injection attacks in corpus | ${safety.injectionAttacks} |
| Blocked (discarded/quarantined) | ${safety.injectionBlocked} |
| Injection success rate | ${safety.injectionSuccessRate} |
| Duplicate active records after 5 identical observations | ${safety.duplicateActiveRecords} |

## Reproduce

\`\`\`bash
pnpm evaluate:memory
\`\`\`
`

writeFileSync('docs/memory-agent/evaluation-results.md', md)
console.log('wrote docs/memory-agent/evaluation-results.md')
